function groupsOf(dict: string[][], word: string): string[][] {
  const w = squash(word);
  return dict.filter((g) => g.some((s) => squash(s) === w));
}

/** 라벨의 동의어들 (자기 자신 포함, 여러 묶음이면 합친다) */
export function labelSynonyms(label: string): string[] {
  return [...new Set(groupsOf(LABEL_SYNONYMS, label).flat())];
}

/** 값의 동의어들 (자기 자신 제외) */
export function valueSynonyms(value: string): string[] {
  const w = squash(value);
  return [...new Set(groupsOf(VALUE_SYNONYMS, value).flat())].filter((s) => squash(s) !== w);
}

/** 사이트가 형식만 바꾼 값인지 (구분자·공백 차이, 하이픈 뺀 전화번호, 2019.03.01 = 20190301) */
export function sameValue(a: string, b: string): boolean {
  if (a === b || squash(a) === squash(b)) return true;
  const da = a.replace(/\D/g, '');
  const letters = /[가-힣a-zA-Z]/;
  return da.length >= 4 && da === b.replace(/\D/g, '') && !letters.test(a) && !letters.test(b);
}
